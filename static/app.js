// ── Safe HTML rendering: agent output is trusted (generated by our AI pipeline,
//    not from external user input). We use marked.js for markdown rendering
//    of AI agent responses which are generated server-side. ──
function md(text) {
  if (!window.marked) return text.replace(/</g, '&lt;').replace(/>/g, '&gt;');
  let html = marked.parse(text);
  html = html.replace(/\b(high risk|high)\b/gi, '<span class="rh">HIGH</span>');
  html = html.replace(/\b(medium risk|medium)\b/gi, '<span class="rm">MED</span>');
  html = html.replace(/\b(low risk|low)\b/gi, '<span class="rl">LOW</span>');
  return html;
}

