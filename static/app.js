const THEME_KEY = 'cn-theme';

function initTheme() {
  const saved = localStorage.getItem(THEME_KEY);
  if (saved) { applyTheme(saved); return; }
  const preferLight = window.matchMedia('(prefers-color-scheme: light)').matches;
  applyTheme(preferLight ? 'light' : 'dark');
}

function applyTheme(theme) {
  document.documentElement.dataset.theme = theme;
  if (el.themeToggle) {
    el.themeToggle.setAttribute('aria-pressed', String(theme === 'light'));
    el.themeToggle.setAttribute('aria-label', 'Switch to ' + (theme === 'light' ? 'dark' : 'light') + ' theme');
    const icon = el.themeToggle.querySelector('.theme-icon');
    if (icon) {
      if (theme === 'light') {
        icon.textContent = 'light_mode';
      } else {
        icon.textContent = 'dark_mode';
      }
    }
  }
  localStorage.setItem(THEME_KEY, theme);
}

el.themeToggle?.addEventListener('click', () => {
  const current = document.documentElement.dataset.theme || 'dark';
  applyTheme(current === 'dark' ? 'light' : 'dark');
});

