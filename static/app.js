function renderHeatmap(data) {
  if (!data.clauses || !data.buyer_analysis || !data.seller_analysis) return;
  window._heatmapData = data;

  const clauses = typeof data.clauses === 'string' ? JSON.parse(data.clauses) : data.clauses;
  const buyerA = typeof data.buyer_analysis === 'string' ? JSON.parse(data.buyer_analysis) : data.buyer_analysis;
  const sellerA = typeof data.seller_analysis === 'string' ? JSON.parse(data.seller_analysis) : data.seller_analysis;

  // Build risk maps: clause_number -> {risk_level, concern, proposed_change}
  const buyerRisks = {};
  const sellerRisks = {};
  (buyerA.clause_risks || []).forEach(r => { buyerRisks[r.clause_number] = r; });
  (sellerA.clause_risks || []).forEach(r => { sellerRisks[r.clause_number] = r; });

  // Determine highest risk per clause
  function maxRisk(num) {
    const levels = { high: 3, medium: 2, low: 1 };
    const b = buyerRisks[num]?.risk_level || '';
    const s = sellerRisks[num]?.risk_level || '';
    const bv = levels[b] || 0;
    const sv = levels[s] || 0;
    const max = Math.max(bv, sv);
    return max === 3 ? 'high' : max === 2 ? 'medium' : max === 1 ? 'low' : 'none';
  }

  const clauseList = clauses.clauses || clauses;
  if (!Array.isArray(clauseList)) return;

  let html = '';
  clauseList.forEach(clause => {
    const risk = maxRisk(clause.number);
    const bRisk = buyerRisks[clause.number];
    const sRisk = sellerRisks[clause.number];
    const riskPill = risk !== 'none'
      ? `<span class="hm-risk-pill rp-${risk}">${risk.toUpperCase()}</span>`
      : '';

    html += `<div class="hm-clause" onclick="this.classList.toggle('open')">
      <div class="hm-clause-head">
        <span class="hm-num risk-${risk}">${clause.number}</span>
        <span class="hm-title">${esc(clause.title)}</span>
        <span class="hm-cat">${esc(clause.category)}</span>
        ${riskPill}
        <span class="material-symbols-outlined hm-chevron" aria-hidden="true">expand_more</span>
      </div>
      <div class="hm-detail"><div class="hm-detail-inner">
        <div class="hm-clause-text">${esc(clause.text)}</div>
        <div class="hm-perspectives">
          <div class="hm-persp buyer-persp">
            <div class="hm-persp-label">Buyer's View</div>
            ${bRisk
              ? `<strong>${esc(bRisk.risk_level.toUpperCase())} RISK</strong><br/>${esc(bRisk.concern)}<br/><em style="color:var(--t3);font-size:.65rem">Suggested: ${esc(bRisk.proposed_change)}</em>`
              : '<span style="color:var(--green)">No concerns raised</span>'}
          </div>
          <div class="hm-persp seller-persp">
            <div class="hm-persp-label">Seller's View</div>
            ${sRisk
              ? `<strong>${esc(sRisk.risk_level.toUpperCase())} RISK</strong><br/>${esc(sRisk.concern)}<br/><em style="color:var(--t3);font-size:.65rem">Suggested: ${esc(sRisk.proposed_change)}</em>`
              : '<span style="color:var(--green)">No concerns raised</span>'}
          </div>
        </div>
      </div></div>
    </div>`;
  });

  // Summary bar
  const highCount = clauseList.filter(c => maxRisk(c.number) === 'high').length;
  const medCount = clauseList.filter(c => maxRisk(c.number) === 'medium').length;
  const lowCount = clauseList.filter(c => maxRisk(c.number) === 'low').length;

  const summary = `<div class="m m-p" style="margin-bottom:.5rem;display:flex;gap:.8rem;align-items:center;flex-wrap:wrap">
    <span style="font-size:.75rem;font-weight:600">${clauseList.length} clauses analyzed</span>
    ${highCount ? `<span class="hm-risk-pill rp-high">${highCount} HIGH</span>` : ''}
    ${medCount ? `<span class="hm-risk-pill rp-medium">${medCount} MEDIUM</span>` : ''}
    ${lowCount ? `<span class="hm-risk-pill rp-low">${lowCount} LOW</span>` : ''}
  </div>`;

  setAgentContent(el.hmClauses, summary + html);
  el.heatmap.classList.remove('closed');
}

