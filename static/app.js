function buildPrintReport() {
  let html = '';

  // Cover: Title + Score + Summary
  html += '<div class="pr-section pr-cover">';
  html += '<h1 class="pr-title">Contract Analysis Report</h1>';
  html += '<p class="pr-date">' + new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }) + '</p>';

  if (window._verdictData) {
    var vd = window._verdictData;
    var sc = vd.overall_fairness_score;
    var clr = sc < 4 ? '#e8710a' : sc > 6 ? '#4285f4' : '#146c2e';
    var lbl = sc < 4 ? 'Favors Seller' : sc > 6 ? 'Favors Buyer' : 'Balanced';
    html += '<div class="pr-score"><span class="pr-score-num" style="color:' + clr + '">' + sc + '/10</span> <span class="pr-score-lbl">' + lbl + '</span></div>';
    if (vd.contract_type) html += '<p class="pr-meta"><strong>Contract Type:</strong> ' + esc(vd.contract_type) + '</p>';
    if (vd.parties && vd.parties.length) html += '<p class="pr-meta"><strong>Parties:</strong> ' + vd.parties.map(esc).join(', ') + '</p>';
    html += '<h2>Executive Summary</h2><p>' + esc(vd.executive_summary) + '</p>';
    html += '<div class="pr-rec"><strong>Recommendation:</strong> ' + esc(vd.recommendation) + '</div>';
  }
  html += '</div>';

  // Risk Heatmap Table
  if (window._heatmapData) {
    var hd = window._heatmapData;
    var clauses = typeof hd.clauses === 'string' ? JSON.parse(hd.clauses) : hd.clauses;
    var buyerA = typeof hd.buyer_analysis === 'string' ? JSON.parse(hd.buyer_analysis) : hd.buyer_analysis;
    var sellerA = typeof hd.seller_analysis === 'string' ? JSON.parse(hd.seller_analysis) : hd.seller_analysis;
    var buyerRisks = {};
    var sellerRisks = {};
    (buyerA.clause_risks || []).forEach(function(r) { buyerRisks[r.clause_number] = r; });
    (sellerA.clause_risks || []).forEach(function(r) { sellerRisks[r.clause_number] = r; });
    var clauseList = clauses.clauses || clauses;

    if (Array.isArray(clauseList) && clauseList.length) {
      html += '<div class="pr-section"><h2>Risk Heatmap</h2>';
      html += '<table class="pr-table"><thead><tr><th>#</th><th>Clause</th><th>Category</th><th>Buyer</th><th>Seller</th></tr></thead><tbody>';
      clauseList.forEach(function(c) {
        var br = buyerRisks[c.number];
        var sr = sellerRisks[c.number];
        var bLevel = br ? br.risk_level : '-';
        var sLevel = sr ? sr.risk_level : '-';
        html += '<tr><td>' + c.number + '</td><td>' + esc(c.title) + '</td><td>' + esc(c.category) + '</td>'
          + '<td class="pr-risk-' + bLevel + '">' + esc(bLevel.toUpperCase()) + '</td>'
          + '<td class="pr-risk-' + sLevel + '">' + esc(sLevel.toUpperCase()) + '</td></tr>';
      });
      html += '</tbody></table></div>';
    }
  }

  // Risk Items from verdict
  if (window._verdictData && window._verdictData.risk_items && window._verdictData.risk_items.length) {
    html += '<div class="pr-section"><h2>Detailed Risk Analysis</h2>';
    window._verdictData.risk_items.forEach(function(item) {
      html += '<div class="pr-risk-item">'
        + '<div class="pr-risk-head"><span class="pr-priority pr-priority-' + item.priority + '">' + esc(item.priority.toUpperCase()) + '</span>'
        + ' Clause ' + item.clause_number + ': ' + esc(item.clause_title) + '</div>'
        + '<div class="pr-risk-body">'
        + '<div><strong>Buyer:</strong> ' + esc(item.buyer_concern) + '</div>'
        + '<div><strong>Seller:</strong> ' + esc(item.seller_concern) + '</div>'
        + '<div><strong>Recommendation:</strong> ' + esc(item.mediator_recommendation) + '</div>'
        + '</div></div>';
    });
    html += '</div>';
  }

  // Redline (changed clauses only)
  var rlData = window._heatmapData && window._heatmapData.redlined_contract;
  if (rlData) {
    var rc = typeof rlData === 'string' ? JSON.parse(rlData) : rlData;
    var changed = (rc.clauses || []).filter(function(c) { return c.changed; });
    if (changed.length) {
      html += '<div class="pr-section"><h2>Suggested Redlines (' + changed.length + ' changes)</h2>';
      if (rc.overall_summary) html += '<p>' + esc(rc.overall_summary) + '</p>';
      changed.forEach(function(c) {
        html += '<div class="pr-redline-item">'
          + '<div class="pr-redline-head">Clause ' + c.clause_number + ': ' + esc(c.change_summary) + '</div>'
          + '<div class="pr-redline-diff">'
          + '<div class="pr-redline-old"><div class="pr-diff-label">Original</div>' + esc(c.original_text) + '</div>'
          + '<div class="pr-redline-new"><div class="pr-diff-label">Revised</div>' + esc(c.revised_text) + '</div>'
          + '</div></div>';
      });
      html += '</div>';
    }
  }

  return html;
}

