// ── TTS: pre-fetch concurrently, play in order ──

function prefetchTTS(agentName) {
  if (ttsCache[agentName]) return;
  const text = T[agentName];
  if (!text) return;
  ttsCache[agentName] = fetch('/api/tts', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ text: text.slice(0, 500), agent_name: agentName }),
  })
    .then(r => r.json())
    .then(r => r.audio ? b64b(r.audio, 'audio/mp3') : null)
    .catch(() => null);
}

function qTTS(a) {
  prefetchTTS(a);
  audioQueue.push(a);
  if (!ttsPlaying) playNext();
}

async function playNext() {
  if (!audioQueue.length) { ttsPlaying = false; return; }
  ttsPlaying = true;
  const a = audioQueue.shift();
  const btn = $(`.mic[data-a="${a}"]`);
  if (btn) btn.classList.add('playing');
  try {
    const blob = await ttsCache[a];
    if (blob) {
      const objectUrl = URL.createObjectURL(blob);
      audio = new Audio(objectUrl);
      audio.playbackRate = 1.15;
      audio.play();
      audio.onended = () => { URL.revokeObjectURL(objectUrl); if (btn) btn.classList.remove('playing'); audio = null; playNext(); };
    } else {
      if (btn) btn.classList.remove('playing');
      playNext();
    }
  } catch {
    if (btn) btn.classList.remove('playing');
    playNext();
  }
}

