async function run(retrying = false) {
  const text = el.inp.value.trim(); if(!text) return;
  await loadMarked();

  if (!retrying) {
    showView('v-analysis');

    // Run PII scan and language detection in parallel (don't block analysis)
    scanPII(text);
    // Language detection already happened on paste if needed

    setAgentContent(el.buyer, skel('Waiting for Buyer\u2019s Lawyer\u2026'));
    setAgentContent(el.seller, skel('Waiting for Seller\u2019s Lawyer\u2026'));
    setAgentContent(el.center, skel('Extracting clauses\u2026'));
    el.verdict.classList.add('closed');
    el.heatmap.classList.add('closed');
    el.redline.classList.add('closed');
    $('#pii-banner')?.remove();
    $('#translate-banner')?.remove();
    resetPips();
    Object.keys(T).forEach(k => delete T[k]);
    ttsCache = {}; audioQueue = []; debR = 0; sseRetryCount = 0;
    debateRounds = []; clauseCardHTML = '';
    window._verdictData = null; window._heatmapData = null; window._buyerData = null; window._sellerData = null;
  }

  if (sseAbortController) sseAbortController.abort();
  sseAbortController = new AbortController();

  try {
    const res = await fetch('/api/analyze', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ contract_text: text }),
      signal: sseAbortController.signal,
    });

    if (!res.ok) throw new Error(`Server error ${res.status}`);

    const reader = res.body.getReader(), dec = new TextDecoder();
    let buf = '';
    while (true) {
      const { value, done } = await reader.read(); if (done) break;
      buf += dec.decode(value, { stream: true });
      const lines = buf.split('\n'); buf = lines.pop() || '';
      for (const l of lines) {
        if (l.startsWith('data: ')) {
          try { onEv(JSON.parse(l.slice(6))); } catch {}
        }
      }
    }
    sseRetryCount = 0;
  } catch (e) {
    if (e.name === 'AbortError') return;
    handleSSEError(e);
  }
}

function handleSSEError(e) {
  if (sseRetryCount < SSE_MAX_RETRIES) {
    sseRetryCount++;
    Object.keys(T).forEach(k => delete T[k]);
    const delay = Math.pow(2, sseRetryCount - 1) * 1000;
    showNetworkBanner(
      `Connection interrupted. Reconnecting in ${delay / 1000}s\u2026 (attempt ${sseRetryCount}/${SSE_MAX_RETRIES})`,
      'warn'
    );
    setTimeout(() => run(true), delay);
  } else {
    showNetworkBanner(
      `Analysis failed after ${SSE_MAX_RETRIES} attempts. Please check your connection and try again.`,
      'error'
    );
    el.go.disabled = false;
    el.go.setAttribute('aria-disabled', 'false');
  }
}

