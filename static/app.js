// ── Events ──
let discCounter = 0;

function onEv(ev) {
  if(ev.done){
    allDone();
    if(ev.session_id){
      lastSessionId = ev.session_id;
      // Fetch all structured data and render visual panels
      loadStructuredResults(ev.session_id);
      enableExports();
      // Auto-save to Firestore + GCS
      fetch(`/api/session/${ev.session_id}/save`, { method: 'POST' }).catch(() => {});
      fetch(`/api/session/${ev.session_id}/store-gcs`, { method: 'POST' }).catch(() => {});
    }
    return;
  }
  if(ev.error){ setAgentContent(el.center, el.center.innerHTML + msg(ev.error, 'p', null, true)); return; }
  const {author,content} = ev;
  if(!content || author==='user') return;
  T[author] = (T[author]||'') + content;
  pip(author,'on');
  highlightPanel(author);

  switch(author){
    case 'ClauseExtractor':
      clauseCardHTML = clauseCard(content);
      setAgentContent(el.center, clauseCardHTML);
      pip('ClauseExtractor','ok');
      break;
    case 'BuyerLawyer':
      if (ev.is_final) {
        setAgentContent(el.buyer, renderStructuredAnalysis(content, 'b'));
        pip('BuyerLawyer','ok');
        prefetchTTS('BuyerLawyer'); qTTS('BuyerLawyer');
      } else {
        // Idea 8: Show streaming progress with token count
        var buyerChars = (T['BuyerLawyer'] || '').length;
        setAgentContent(el.buyer, statusCard('Buyer\'s Lawyer', 'Analyzing clauses... ' + (buyerChars > 100 ? Math.round(buyerChars/100)*100 + '+ chars' : ''), 'blue'));
      }
      break;
    case 'SellerLawyer':
      if (ev.is_final) {
        setAgentContent(el.seller, renderStructuredAnalysis(content, 's'));
        pip('SellerLawyer','ok');
        prefetchTTS('SellerLawyer'); qTTS('SellerLawyer');
      } else {
        var sellerChars = (T['SellerLawyer'] || '').length;
        setAgentContent(el.seller, statusCard('Seller\'s Lawyer', 'Analyzing clauses... ' + (sellerChars > 100 ? Math.round(sellerChars/100)*100 + '+ chars' : ''), 'orange'));
      }
      break;
    case 'BuyerRebuttal':
      pip('DebateRounds','on'); rmSkel(el.center);
      if (ev.is_final) {
        debR++;
        // Try content first (clean final event), then accumulated T[] as fallback
        var brText = tryParseJSON(content) ? content : T['BuyerRebuttal'];
        var brRound = getRebuttalRound(brText, Math.ceil(debR/2));
        if (!debateRounds[brRound - 1]) debateRounds[brRound - 1] = { round: brRound, buyer: '', seller: '' };
        debateRounds[brRound - 1].buyer = renderStructuredDebate(brText, 'b', 'Buyer argues');
        T['BuyerRebuttal'] = ''; // reset for next round
        renderDebateArena();
        scr(el.center); prefetchTTS('BuyerRebuttal'); qTTS('BuyerRebuttal');
      } else {
        // Idea 8: Show which round and side is active
        var curRound = Math.ceil((debR + 1) / 2);
        showDebateStatus('Round ' + curRound + ': Buyer and Seller are debating...');
      }
      break;
    case 'SellerRebuttal':
      pip('DebateRounds','on');
      if (ev.is_final) {
        debR++;
        var srText = tryParseJSON(content) ? content : T['SellerRebuttal'];
        var srRound = getRebuttalRound(srText, Math.ceil(debR/2));
        if (!debateRounds[srRound - 1]) debateRounds[srRound - 1] = { round: srRound, buyer: '', seller: '' };
        debateRounds[srRound - 1].seller = renderStructuredDebate(srText, 's', 'Seller counters');
        T['SellerRebuttal'] = ''; // reset for next round
        renderDebateArena();
        scr(el.center); prefetchTTS('SellerRebuttal'); qTTS('SellerRebuttal');
      } else {
        var curRound = Math.ceil((debR + 1) / 2);
        showDebateStatus('Round ' + curRound + ': Buyer and Seller are debating...');
      }
      break;
    case 'Mediator':
      pip('DebateRounds','ok'); pip('Mediator','on');
      if (ev.is_final) {
        // Try content first (clean final), then accumulated T[]
        var medText = tryParseJSON(content) ? content : T['Mediator'];
        showVerdict(medText);
        pip('Mediator','ok'); prefetchTTS('Mediator'); qTTS('Mediator');
      } else {
        // Idea 8: Show mediator deliberation status
        showDebateStatus('Mediator is deliberating...');
      }
      break;
    case 'Redliner':
      pip('Redliner','on');
      if (!ev.is_final) {
        showDebateStatus('Drafting redline suggestions...');
      }
      // Don't render from streaming - wait for done event to fetch structured data
      if (ev.is_final) {
        pip('Redliner','ok');
      }
      break;
    default:
      rmSkel(el.center);
      setAgentContent(el.center, el.center.innerHTML + renderDebate(content, 'p', author));
      scr(el.center);
  }
}

