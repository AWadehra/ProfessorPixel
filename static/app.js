// HTML entity escaping for untrusted AI-generated strings inserted via innerHTML
function esc(s) {
  if (typeof s !== 'string') return '';
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

/* ── marked.js loader (deferred, non-blocking) ── */
let markedReady = null;
function loadMarked() {
  if (markedReady) return markedReady;
  markedReady = new Promise((resolve, reject) => {
    if (window.marked) { marked.setOptions({ breaks: true, gfm: true }); resolve(); return; }
    const s = document.createElement('script');
    s.src = 'https://cdn.jsdelivr.net/npm/marked@15.0.7/marked.min.js';
    s.onload = () => { marked.setOptions({ breaks: true, gfm: true }); resolve(); };
    s.onerror = reject;
    document.head.appendChild(s);
  });
  return markedReady;
}
