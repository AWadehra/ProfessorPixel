// Auto-highlight step on scroll
if ('IntersectionObserver' in window) {
  const stepObserver = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      const id = entry.target.id;
      const stepName = Object.keys(STEP_TARGETS).find(k => STEP_TARGETS[k] === id);
      if (stepName) {
        $$('.step').forEach(s => s.classList.remove('active'));
        $(`.step[data-s="${stepName}"]`)?.classList.add('active');
      }
    });
  }, { threshold: 0.3 });

  Object.values(STEP_TARGETS).forEach(id => {
    const target = document.getElementById(id);
    if (target) stepObserver.observe(target);
  });
}
